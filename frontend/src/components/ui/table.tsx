import * as React from "react"
import { cn } from "@/utils/cn"

/**
 * ═══════════════════════════════════════════════════════════════════════
 * Table — Canonical table component suite for JobFinder PRO
 *
 * Implements accessible, responsive table primitives matching the
 * unified design tokens (dark theme, glass/surface borders, smooth hover).
 * ═══════════════════════════════════════════════════════════════════════
 */

const Table = React.forwardRef<
  HTMLTableElement,
  React.HTMLAttributes<HTMLTableElement> & { containerClassName?: string }
>(({ className, containerClassName, ...props }, ref) => (
  <div className={cn("relative w-full overflow-x-auto custom-scrollbar rounded-2xl border border-border bg-surface-elevated/50", containerClassName)}>
    <table
      ref={ref}
      className={cn("w-full caption-bottom text-sm text-foreground", className)}
      {...props}
    />
  </div>
))
Table.displayName = "Table"

const TableHeader = React.forwardRef<
  HTMLTableSectionElement,
  React.HTMLAttributes<HTMLTableSectionElement>
>(({ className, ...props }, ref) => (
  <thead
    ref={ref}
    className={cn("[&_tr]:border-b [&_tr]:border-border bg-surface-muted/50", className)}
    {...props}
  />
))
TableHeader.displayName = "TableHeader"

const TableBody = React.forwardRef<
  HTMLTableSectionElement,
  React.HTMLAttributes<HTMLTableSectionElement>
>(({ className, ...props }, ref) => (
  <tbody
    ref={ref}
    className={cn("[&_tr:last-child]:border-0 divide-y divide-border/60", className)}
    {...props}
  />
))
TableBody.displayName = "TableBody"

